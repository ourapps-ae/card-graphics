// Writes tests/fixtures/cards.json: expected card models from the TypeScript, for the native checks.
import { writeFileSync } from "node:fs";
import { PIPS, allCards, cardMetrics, dealPlan, faceModel, flipState } from "../implementation/web/card-model.ts";

const FRENCH: Record<string, string> = { J: "V", Q: "D", K: "R", A: "A", T: "10" };

export function build(): string {
  const faces = allCards().map((code) => ({ code, model: faceModel(code, { rankLabel: (r) => FRENCH[r] ?? r }) }));
  const court = faceModel("Qh", { theme: "royal", artFor: (n) => (n === "card-royal-queen.png" ? "queen.png" : null) });
  const backs = [faceModel(null), faceModel(null, { theme: "royal", artFor: () => "back.png" }), faceModel(null, { theme: "royal", artFor: () => "back.png", backStyle: "stripes" })];
  const flips = [0, 0.1, 0.25, 0.5, 0.6, 0.75, 1].map((p) => ({ progress: p, ...flipState(p) }));
  return JSON.stringify({
    faces, court, backs, flips, pips: PIPS,
    metrics: [[56, "rounded"], [100, "soft"], [33, "square"]].map(([w, c]) => ({ width: w, corner: c, ...cardMetrics(w as number, c as never) })),
    deal: dealPlan(4),
  }, null, 1) + "\n";
}

// The faces as Kotlin source rows, so the Android check needs no JSON library.
export function buildKotlin(): string {
  const rows = allCards().map((code) => {
    const m = faceModel(code, { rankLabel: (r) => FRENCH[r] ?? r });
    if (m.kind !== "face") throw new Error(code);
    const c = m.centre;
    const detail = c.type === "pips" ? c.pips.map((p) => `${p.x}:${p.y}:${Number(p.flip)}:${Number(p.small)}`).join(";") : c.type === "ace" ? c.pip : c.type === "rank" ? c.text : "";
    return `    arrayOf("${code}", ${Number(m.red)}, "${m.rankText}", ${Number(m.ten)}, "${c.type}", "${detail}"),`;
  });
  return `// Generated by tests/make-fixtures.ts from the TypeScript card model (French rank labels).
// code, red, rankText, ten, centre type, centre detail (pips as x:y:flip:small separated by ;)
val EXPECTED_FACES = listOf(
${rows.join("\n")}
)
`;
}

if (import.meta.main) {
  writeFileSync(new URL("fixtures/cards.json", import.meta.url), build());
  writeFileSync(new URL("android/Expected.kt", import.meta.url), buildKotlin());
}
